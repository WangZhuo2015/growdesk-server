export function getWhoStandard(gender?: string | null): GrowthStandardSet {
  return gender === "boy" || gender === "male" ? WHO_STANDARDS_BOYS : WHO_STANDARDS_GIRLS;
}

/**
 * Estimates the growth percentile (1–99) for a given gender, metric, age in months (can be fractional), and measurement value.
 * Uses linear interpolation across month milestones.
 */
export function estimatePercentile(
  gender: string | null | undefined,
  metric: "weight" | "height" | "headCircumference",
  ageMonths: number,
  value: number
): number {
  if (value == null || Number.isNaN(value) || value <= 0) return 50;

  const std = getWhoStandard(gender);
  const data = std[metric];
  const clampedAge = Math.min(Math.max(0, ageMonths), 36);

  const lowIdx = Math.floor(clampedAge);
  const highIdx = Math.min(36, Math.ceil(clampedAge));
  const fraction = clampedAge - lowIdx;

  const lerp = (arr: readonly number[]) => {
    const vLow = arr[lowIdx] ?? arr[0] ?? 0;
    const vHigh = arr[highIdx] ?? vLow;
    return vLow + (vHigh - vLow) * fraction;
  };

  const p3 = lerp(data.P3);
  const p15 = lerp(data.P15);
  const p50 = lerp(data.P50);
  const p85 = lerp(data.P85);
  const p97 = lerp(data.P97);

  if (value >= p97) return 97;
  if (value <= p3) return 3;
  if (value >= p85) {
    const span = p97 - p85;
    return span > 0 ? Math.min(97, Math.round(85 + ((value - p85) / span) * 12)) : 85;
  }
  if (value >= p50) {
    const span = p85 - p50;
    return span > 0 ? Math.min(85, Math.round(50 + ((value - p50) / span) * 35)) : 50;
  }
  if (value >= p15) {
    const span = p50 - p15;
    return span > 0 ? Math.min(50, Math.round(15 + ((value - p15) / span) * 35)) : 15;
  }
  const span = p15 - p3;
  return span > 0 ? Math.min(15, Math.round(3 + ((value - p3) / span) * 12)) : 3;
}

export function buildWhoGrowthChartSet(gender?: string | null): WhoGrowthChartSet {
  const std = getWhoStandard(gender);
  const formatPoint = (p: PercentileData, idx: number, precision: number): WhoPercentilePoint => ({
    monthAge: idx,
    p3: (p.P3[idx] ?? 0).toFixed(precision),
    p15: (p.P15[idx] ?? 0).toFixed(precision),
    p50: (p.P50[idx] ?? 0).toFixed(precision),
    p85: (p.P85[idx] ?? 0).toFixed(precision),
    p97: (p.P97[idx] ?? 0).toFixed(precision),
  });

  return {
    weightForAge: std.months.map((m) => formatPoint(std.weight, m, 2)),
    heightForAge: std.months.map((m) => formatPoint(std.height, m, 1)),
    headCircumferenceForAge: std.months.map((m) => formatPoint(std.headCircumference, m, 1)),
  };
}
